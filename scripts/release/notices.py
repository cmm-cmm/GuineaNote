"""Generate THIRD_PARTY_NOTICES.txt for release archives (release plan R0.6).

Offline: reads `cargo metadata --locked` for the Windows and Linux release
targets, keeps the crates the three binaries link (normal and build
dependencies, not dev-dependencies), and copies each crate's own license and
notice files from the local Cargo registry. Identical license texts are
printed once with the list of crates that ship them. Fails if a linked crate
has no license file and no SPDX expression.

    python -X utf8 scripts/release/notices.py [--out target/release-notices/THIRD_PARTY_NOTICES.txt]
"""
