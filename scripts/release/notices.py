def metadata(target):
    output = subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked", "--filter-platform", target],
        cwd=ROOT, check=True, capture_output=True, text=True, encoding="utf-8").stdout
    return json.loads(output)


def linked(meta):
    """Package ids reachable from workspace members through non-dev edges."""
    nodes = {node["id"]: node for node in meta["resolve"]["nodes"]}
    seen, stack = set(), list(meta["workspace_members"])
    while stack:
        current = stack.pop()
        if current in seen:
            continue
        seen.add(current)
        for dep in nodes[current]["deps"]:
            kinds = {kind["kind"] for kind in dep["dep_kinds"]}
            if kinds - {"dev"}:
                stack.append(dep["pkg"])
    return seen - set(meta["workspace_members"])


def license_files(package):
    folder = Path(package["manifest_path"]).parent
    files = []
    for path in sorted(folder.iterdir()):
        if path.is_file() and path.name.lower().startswith(LICENSE_PREFIXES):
            files.append(path)
    if package.get("license_file"):
        extra = folder / package["license_file"]
        if extra.is_file() and extra not in files:
            files.append(extra)
    return files


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--out", type=Path,
                        default=ROOT / "target" / "release-notices" / "THIRD_PARTY_NOTICES.txt")
    args = parser.parse_args()
    packages = {}
    for target in TARGETS:
        meta = metadata(target)
        by_id = {package["id"]: package for package in meta["packages"]}
        for package_id in linked(meta):
            packages[package_id] = by_id[package_id]
    texts = {}   # sha256 -> (text, [crate labels])
    entries = []
    missing = []
    for package in sorted(packages.values(), key=lambda p: (p["name"], p["version"])):
        label = f'{package["name"]} {package["version"]}'
        files = license_files(package)
        refs = []
        if not files:
            spdx = package.get("license")
            if spdx not in STANDARD:
                missing.append(label)
                continue
            authors = ", ".join(a.split(" <")[0] for a in package.get("authors") or []) or "the authors"
            text = (f"{label} ships no license file; standard {spdx} text, authors "
                    "from its manifest:\n\n" + STANDARD[spdx].format(authors=authors))
            digest = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(digest, [text, []])[1].append(f"{label} (standard {spdx})")
            refs.append(digest)
        for path in files:
            text = path.read_text(encoding="utf-8", errors="replace").strip() + "\n"
            digest = hashlib.sha256(text.encode()).hexdigest()[:12]
            texts.setdefault(digest, [text, []])[1].append(f"{label} ({path.name})")
            refs.append(digest)
        entries.append((label, package.get("license") or "see files",
                        package.get("repository") or "", refs))
    if missing:
        print("crates without a license file or a known standard license: "
              + ", ".join(missing), file=sys.stderr)
        return 1
    lines = [
        "Guinea Note — third-party notices",
        "",
        "Guinea Note (MIT, see LICENSE) is built from the following crates (linked",
        f"code plus build tools) for {', '.join(TARGETS)}. Each crate's license",
        "terms follow, with",
        "identical texts printed once. Generated by scripts/release/notices.py.",
        "",
        "== Crates ==",
        "",
    ]
    for label, license_, repository, refs in entries:
        lines.append(f"{label}  [{license_}]  {repository}".rstrip())
        if refs:
            lines.append("    texts: " + ", ".join(refs))
    lines += ["", "== License texts ==", ""]
    for digest, (text, users) in sorted(texts.items(), key=lambda item: item[1][1][0]):
        lines.append(f"---- [{digest}] used by: " + "; ".join(users))
        lines.append("")
        lines.append(text)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(json.dumps({"crates": len(entries), "distinct_texts": len(texts),
                      "bytes": args.out.stat().st_size, "out": str(args.out)}))
    return 0


if __name__ == "__main__":
    sys.exit(main())
